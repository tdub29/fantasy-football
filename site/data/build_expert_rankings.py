"""Build window.EXPERT_RANKINGS from _expert_sources.json.

Each source in the input JSON is one analyst's ranking set, rendered as a
context column beside players (alongside the Vegas market + Sleeper columns).
This script resolves each player to a Sleeper ID (exact match beats runtime
name matching) and writes site/data/expert-rankings.js.

Add a new expert: append a source object to _expert_sources.json, then run
    python site/data/build_expert_rankings.py
Shape per player: {pos, posRank, name, team, tier?, note?}. Overall-scope
sources use {rank} instead of {posRank}.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLAYERS_PATH = ROOT / "players-nfl.json"
INPUT_PATH = Path(__file__).resolve().parent / "_expert_sources.json"
OUTPUT_PATH = Path(__file__).resolve().parent / "expert-rankings.js"
OFFENSE = {"QB", "RB", "WR", "TE"}
# Analysts use nicknames Sleeper does not. Same map as build_jacob_gibbs.py.
NAME_ALIASES = {"Hollywood Brown": "Marquise Brown"}


def norm(value: str) -> str:
    value = (value or "").lower().replace(".", "").replace("'", "")
    value = re.sub(r"\s+(jr|sr|iii|ii|iv)\b", "", value)
    return re.sub(r"[^a-z0-9 -]", "", re.sub(r"\s+", " ", value)).strip()


def sleeper_index() -> dict:
    players = json.loads(PLAYERS_PATH.read_text(encoding="utf-8"))
    index: dict[str, list] = {}
    for pid, p in players.items():
        name = p.get("full_name") or p.get("name")
        if name:
            index.setdefault(norm(name), []).append((pid, p))
    return index


def resolve(name: str, pos: str, team: str, index: dict) -> str | None:
    candidates = index.get(norm(NAME_ALIASES.get(name, name)), [])
    if len(candidates) == 1:
        return candidates[0][0]
    for pid, p in candidates:
        positions = {p.get("position"), *(p.get("fantasy_positions") or [])}
        if pos in positions and (not team or p.get("team") == team):
            return pid
    for pid, p in candidates:
        positions = {p.get("position"), *(p.get("fantasy_positions") or [])}
        if pos in positions:
            return pid
    return candidates[0][0] if candidates else None


def main() -> None:
    index = sleeper_index()
    sources = json.loads(INPUT_PATH.read_text(encoding="utf-8"))
    unmatched: list[str] = []
    for src in sources:
        for pl in src["players"]:
            pid = resolve(pl["name"], pl.get("pos", ""), pl.get("team", ""), index)
            if pid:
                pl["sleeperId"] = pid
            else:
                unmatched.append(f'{src["id"]}: {pl["name"]} ({pl.get("pos")})')
    payload = json.dumps(sources, ensure_ascii=False, separators=(",", ":"))
    OUTPUT_PATH.write_text(
        "// Generated by build_expert_rankings.py from _expert_sources.json. Do not edit by hand.\n"
        "// Expert ranking sources -> one context column per source beside players.\n"
        f"window.EXPERT_RANKINGS={payload};\n",
        encoding="utf-8",
    )
    total = sum(len(s["players"]) for s in sources)
    matched = total - len(unmatched)
    print(f"Wrote {len(sources)} source(s), {total} players ({matched} Sleeper matches) to {OUTPUT_PATH.name}")
    if unmatched:
        print("UNMATCHED (falls back to runtime name match):")
        for u in unmatched:
            print("  " + u)


if __name__ == "__main__":
    main()
