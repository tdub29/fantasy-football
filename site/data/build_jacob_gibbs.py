"""Build dated Jacob Gibbs half-PPR rankings for dynasty context columns."""
from __future__ import annotations

import argparse
import csv
import json
import re
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLAYERS_PATH = ROOT / "players-nfl.json"
OUTPUT_PATH = ROOT / "site" / "data" / "jacob-gibbs.js"
OFFENSE = {"QB", "RB", "WR", "TE"}
NAME_ALIASES = {"Hollywood Brown": "Marquise Brown"}
# Sleeper's codes, for the match only. The board keeps whatever the source printed.
TEAM_ALIASES = {"JAC": "JAX", "WSH": "WAS", "LA": "LAR"}


def norm(value: str) -> str:
    value = value.lower().replace(".", "").replace("'", "")
    value = re.sub(r"\s+(jr|sr|iii|ii|iv)\b", "", value)
    return re.sub(r"[^a-z0-9 -]", "", re.sub(r"\s+", " ", value)).strip()


def parse_int(value: str | None) -> int | None:
    match = re.search(r"\d+", value or "")
    return int(match.group()) if match else None


def sleeper_index() -> dict[str, list[tuple[str, dict]]]:
    players = json.loads(PLAYERS_PATH.read_text(encoding="utf-8"))
    index: dict[str, list[tuple[str, dict]]] = {}
    for player_id, player in players.items():
        name = player.get("full_name") or player.get("name")
        if name:
            index.setdefault(norm(name), []).append((player_id, player))
    return index


def sleeper_id(name: str, pos: str, team: str, index: dict) -> str | None:
    candidates = index.get(norm(NAME_ALIASES.get(name, name)), [])
    team = TEAM_ALIASES.get(team, team)
    if len(candidates) == 1:
        return candidates[0][0]
    for player_id, player in candidates:
        positions = {player.get("position"), *(player.get("fantasy_positions") or [])}
        if pos in positions and (not team or player.get("team") == team):
            return player_id
    for player_id, player in candidates:
        positions = {player.get("position"), *(player.get("fantasy_positions") or [])}
        if pos in positions:
            return player_id
    return None


def build(source_path: Path, updated_at: str, source_label: str, title: str) -> dict:
    index = sleeper_index()
    players = []
    seen_ranks = set()
    with source_path.open(encoding="utf-8-sig", newline="") as source:
        for row in csv.DictReader(source):
            name = (row.get("PLAYER NAME") or "").strip()
            rank_text = (row.get("RK") or "").strip()
            pos_text = (row.get("POS") or "").strip().upper()
            match = re.fullmatch(r"([A-Z]+)(\d+)", pos_text)
            if not name or not rank_text or not match or match.group(1) not in OFFENSE:
                continue
            rank = int(rank_text)
            if rank in seen_ranks:
                raise ValueError(f"duplicate overall rank: {rank}")
            seen_ranks.add(rank)
            pos, pos_rank = match.group(1), int(match.group(2))
            team = (row.get("TEAM") or "FA").strip().upper() or "FA"
            players.append({
                "rank": rank,
                "tier": int((row.get("TIERS") or "0").strip() or 0),
                "name": name,
                "team": team,
                "pos": pos,
                "posRank": pos_rank,
                "bye": parse_int(row.get("BYE")),
                "sos": parse_int(row.get("SOS")),
                "ecrVsAdp": (row.get("ECR VS ADP") or "").strip(),
                "sleeperId": sleeper_id(name, pos, team, index),
            })
    players.sort(key=lambda player: player["rank"])
    if not players or players[0]["name"] != "Jahmyr Gibbs" or players[0]["rank"] != 1:
        raise ValueError("unexpected Jacob Gibbs ranking leader")
    return {
        "source": source_label,
        "title": title,
        "format": "redraft_half_ppr",
        "updatedAt": updated_at,
        "dynastyUse": "Season production context only; KTC remains dynasty value source of truth.",
        "players": players,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("--output", type=Path, default=OUTPUT_PATH)
    parser.add_argument("--updated-at", help="YYYY-MM-DD; defaults to source file modified date")
    parser.add_argument("--source", default="Jacob Gibbs via FantasyPros", help="publisher credit")
    parser.add_argument("--title", default="2026 Draft Rankings", help="board title")
    args = parser.parse_args()
    updated_at = args.updated_at or datetime.fromtimestamp(args.input.stat().st_mtime).date().isoformat()
    data = build(args.input, updated_at, args.source, args.title)
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    args.output.write_text(
        "// Generated by build_jacob_gibbs.py. Redraft signal only; do not edit.\n"
        f"window.JACOB_GIBBS_RANKINGS={payload};\n",
        encoding="utf-8",
    )
    matched = sum(bool(player["sleeperId"]) for player in data["players"])
    print(f"Wrote {len(data['players'])} offensive players ({matched} Sleeper matches) to {args.output}")


if __name__ == "__main__":
    main()
